#!/usr/bin/env bash
# =========================================================================
# Village Setu — One-Shot Local Setup Script for WSL Ubuntu Linux
# =========================================================================
# This script does EVERYTHING needed to run the app locally:
#   1. Checks Python 3.10+ is installed
#   2. Creates a Python virtual environment (.venv/)
#   3. Installs all Python dependencies
#   4. Generates a .env file with random JWT_SECRET and ENCRYPTION_KEY
#   5. Initializes the SQLite database (creates tables + seeds admin)
#   6. Starts the server at http://localhost:8000
#
# Usage:
#   chmod +x setup.sh
#   ./setup.sh
#
# After first run, use run.sh to start the server again.
# =========================================================================
set -e

# Color codes for pretty output
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
RED='\033[0;31m'
NC='\033[0m' # No Color

echo -e "${BLUE}╔══════════════════════════════════════════════════════════╗${NC}"
echo -e "${BLUE}║  आशापुरी कॉम्प्युटर सर्विस कर्ले — Local Setup           ║${NC}"
echo -e "${BLUE}║  Village Setu — Offline Local Installation              ║${NC}"
echo -e "${BLUE}╚══════════════════════════════════════════════════════════╝${NC}"
echo ""

# --- Step 0: Navigate to script directory ---------------------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"
echo -e "${BLUE}[0/6] Working directory: $SCRIPT_DIR${NC}"

# --- Step 1: Check Python version ----------------------------------------
echo ""
echo -e "${BLUE}[1/6] Checking Python installation...${NC}"
if command -v python3 &> /dev/null; then
    PY_VERSION=$(python3 -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')
    PY_MAJOR=$(echo $PY_VERSION | cut -d. -f1)
    PY_MINOR=$(echo $PY_VERSION | cut -d. -f2)
    if [ "$PY_MAJOR" -ge 3 ] && [ "$PY_MINOR" -ge 10 ]; then
        echo -e "${GREEN}  ✓ Python $PY_VERSION found${NC}"
    else
        echo -e "${RED}  ✗ Python 3.10+ required, found $PY_VERSION${NC}"
        echo -e "${YELLOW}  Install with: sudo apt update && sudo apt install -y python3 python3-pip python3-venv${NC}"
        exit 1
    fi
else
    echo -e "${RED}  ✗ Python 3 not found${NC}"
    echo -e "${YELLOW}  Install with: sudo apt update && sudo apt install -y python3 python3-pip python3-venv${NC}"
    exit 1
fi

# --- Step 2: Create virtual environment -----------------------------------
echo ""
echo -e "${BLUE}[2/6] Creating Python virtual environment...${NC}"
if [ -d ".venv" ]; then
    echo -e "${YELLOW}  ⚠ .venv already exists, reusing it${NC}"
else
    python3 -m venv .venv
    echo -e "${GREEN}  ✓ Virtual environment created at .venv/${NC}"
fi

# Activate it
source .venv/bin/activate

# Upgrade pip
echo -e "${BLUE}  Upgrading pip...${NC}"
pip install --upgrade pip --quiet

# --- Step 3: Install dependencies -----------------------------------------
echo ""
echo -e "${BLUE}[3/6] Installing Python dependencies...${NC}"
pip install -r requirements.txt --quiet
echo -e "${GREEN}  ✓ Dependencies installed${NC}"

# --- Step 4: Generate .env file -------------------------------------------
echo ""
echo -e "${BLUE}[4/6] Generating .env file...${NC}"
if [ -f ".env" ]; then
    echo -e "${YELLOW}  ⚠ .env already exists, keeping existing config${NC}"
    echo -e "${YELLOW}  (Delete .env to regenerate with new secrets)${NC}"
else
    # Generate random secrets
    JWT_SECRET=$(python3 -c "import secrets; print(secrets.token_urlsafe(64))")
    ENCRYPTION_KEY=$(python3 -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())")

    cat > .env << EOF
# Village Setu — Local Configuration
# Auto-generated by setup.sh on $(date)
# Edit this file to customize, then restart the server.

# Database — SQLite (local file, no internet needed)
DATABASE_URL=sqlite:///./village_setu.db

# Auth — auto-generated random secrets
JWT_SECRET=$JWT_SECRET
JWT_ALGORITHM=HS256
JWT_EXPIRE_MINUTES=480

# Bootstrap admin (login credentials for first admin)
ADMIN_EMAIL=admin@villagesetu.gov.in
ADMIN_PASSWORD=Admin@12345

# File uploads
UPLOAD_FOLDER=uploads
MAX_UPLOAD_MB=5

# Aadhaar encryption key (auto-generated)
ENCRYPTION_KEY=$ENCRYPTION_KEY

# CORS
CORS_ORIGINS=*

# App
APP_NAME=Village Setu
APP_ENV=local
EOF
    echo -e "${GREEN}  ✓ .env file created with random secrets${NC}"
    echo -e "${YELLOW}  ℹ Admin login: admin@villagesetu.gov.in / Admin@12345${NC}"
fi

# --- Step 5: Initialize database ------------------------------------------
echo ""
echo -e "${BLUE}[5/6] Initializing SQLite database...${NC}"
# Create uploads folder
mkdir -p uploads
# Initialize the database (creates tables + seeds admin + super admin)
python3 -c "
from backend.database import init_db, seed_admin_if_missing
init_db()
seed_admin_if_missing()
print('  ✓ Database initialized — tables created, admin user seeded')
"
echo -e "${GREEN}  ✓ Database file: village_setu.db${NC}"

# --- Step 6: Start the server --------------------------------------------
echo ""
echo -e "${BLUE}[6/6] Starting the server...${NC}"
echo ""
echo -e "${GREEN}╔══════════════════════════════════════════════════════════╗${NC}"
echo -e "${GREEN}║  ✅ Setup complete!                                      ║${NC}"
echo -e "${GREEN}║                                                          ║${NC}"
echo -e "${GREEN}║  🌐 Open in browser:  http://localhost:8000               ║${NC}"
echo -e "${GREEN}║                                                          ║${NC}"
echo -e "${GREEN}║  👤 Login:                                            ║${NC}"
echo -e "${GREEN}║     Email:    admin@villagesetu.gov.in                   ║${NC}"
echo -e "${GREEN}║     Password: Admin@12345                                ║${NC}"
echo -e "${GREEN}║                                                          ║${NC}"
echo -e "${GREEN}║  🛑 Press Ctrl+C to stop the server                       ║${NC}"
echo -e "${GREEN}║                                                          ║${NC}"
echo -e "${GREEN}║  📋 Next time, run: ./run.sh                             ║${NC}"
echo -e "${GREEN}╚══════════════════════════════════════════════════════════╝${NC}"
echo ""

# Start uvicorn server
exec python3 -m uvicorn backend.main:app --host 0.0.0.0 --port 8000
